async function seedDatabase() {
  console.log('🔗 Connecting to MongoDB...')
  const client = new MongoClient(MONGODB_URI, {
    connectTimeoutMS: 30000,
    socketTimeoutMS: 60000,
    serverSelectionTimeoutMS: 30000,
  })

  try {
    await client.connect()
    console.log('✅ Connected to MongoDB successfully')

    const db = client.db('medai_academy')
    const coursesCollection = db.collection('courses')

    // Check if courses already exist
    const existingCount = await coursesCollection.countDocuments()
    console.log(`📊 Found ${existingCount} existing courses`)

    // Always clear and re-seed with real medical courses
    if (existingCount > 0) {
      await coursesCollection.deleteMany({})
      console.log('🗑️  Cleared existing courses')
    }

    // Insert courses
    const result = await coursesCollection.insertMany(courses)
    console.log(`✅ Successfully inserted ${result.insertedCount} courses`)

    // Verify insertion
    const newCount = await coursesCollection.countDocuments()
    console.log(`📊 Total courses now: ${newCount}`)

    // Print course summary
    for (const course of courses) {
      console.log(`  📚 ${course.titleAr}: ${course.lessonsData.length} lessons, ${course.price} ر.ي, ${course.category}`)
    }

    console.log('\n🎉 Seed completed successfully!')

  } catch (error) {
    console.error('❌ Seed failed:', error)
    process.exit(1)
  } finally {
    await client.close()
    console.log('🔌 Database connection closed')
  }
}

seedDatabase()
