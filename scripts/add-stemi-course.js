const IMAGE_DIR = path.join(__dirname, '..', 'course-images', 'stemi');

async function compressAndEncodeImage(filename) {
  const filePath = path.join(IMAGE_DIR, filename);
  if (!fs.existsSync(filePath)) {
    console.log(`⚠️ Image not found: ${filename}`);
    return null;
  }
  const compressed = await sharp(filePath)
    .resize(800, 800, { fit: 'inside', withoutEnlargement: true })
    .jpeg({ quality: 70 })
    .toBuffer();
  const base64 = compressed.toString('base64');
  const dataUrl = `data:image/jpeg;base64,${base64}`;
  console.log(`  ✅ ${filename}: ${(Buffer.byteLength(dataUrl) / 1024).toFixed(1)} KB`);
  return dataUrl;
}

